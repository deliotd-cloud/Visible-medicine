import path from 'node:path';

export const catalogPaths = Object.freeze([
  'atlas-review/public/models/bodyparts3d/full-body/catalog.json',
  'public/atlas-runtime/head-neck/models/bodyparts3d/full-body/catalog.json',
]);
export const schemaPaths = Object.freeze([
  'atlas-review/app/body-types.ts',
  'atlas-review/lib/anatomy-coordinates.ts',
]);
const digest = value => typeof value === 'string' && /^[a-f0-9]{64}$/.test(value);

export function declarationFor(relativeJsonPath, catalogSha256, schemaSha256) {
  if (!catalogPaths.includes(relativeJsonPath) || !digest(catalogSha256) || !digest(schemaSha256))
    throw Error('Unsupported catalog declaration input');
  const target = path.posix.dirname(relativeJsonPath);
  let specifier = path.posix.relative(target, 'atlas-review/app/body-types');
  if (!specifier.startsWith('.')) specifier = './' + specifier;
  return '// Generated by scripts/atlas-catalog-types.mjs; do not hand edit.\n' +
    `// Catalog SHA-256: ${catalogSha256}\n// Contract SHA-256: ${schemaSha256}\n` +
    `import type {BodyCatalog} from '${specifier}';\n` +
    'declare const catalog: BodyCatalog;\nexport default catalog;\n';
}
