import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const sha = value => createHash('sha256').update(value).digest('hex');
const read = path => JSON.parse(readFileSync(path));
const source = read('atlas-review/manifest.json');
const receipt = read('atlas-review/integration-inputs.json');
const viewer = read('public/atlas-review-viewer/manifest.json');
assert.equal(source.revision, receipt.sourceCommit);
assert.equal(source.revision, viewer.sourceCommit);
for (const file of source.files) assert.equal(sha(readFileSync('atlas-review/'+file.path)), file.importedSha256, 'Imported Atlas file changed: '+file.path);
for (const file of receipt.inputs) assert.equal(sha(readFileSync(file.path)), file.sha256, 'Review input changed; rebind and rebuild: '+file.path);
assert.equal(sha(JSON.stringify(receipt.inputs)), receipt.sha256);
assert.equal(source.websiteIntegrationSha256, receipt.sha256);
assert.equal(viewer.websiteIntegrationSha256, receipt.sha256);
for (const file of viewer.files) assert.equal(sha(readFileSync('public/atlas-review-viewer/'+file.path)), file.sha256, 'Review viewer artifact changed: '+file.path);
assert.equal(viewer.personalRecordsIncluded, false);
assert.equal(viewer.mode, 'production', 'Rebuild the review viewer without --debug before publication.');
console.log(JSON.stringify({sourceCommit:source.revision,integrationHash:receipt.sha256,sourceFiles:source.files.length,viewerFiles:viewer.files.length,packages:viewer.packages.length}));
