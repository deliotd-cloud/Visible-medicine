// Compiler-only companion for the native full-body catalog. Runtime JSON is untouched.
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import ts from 'typescript';

export const catalogPath = 'public/models/bodyparts3d/full-body/catalog.json';
export const declarationPath = 'public/models/bodyparts3d/full-body/catalog.d.json.ts';
export const schemaPaths = Object.freeze(['app/body-types.ts', 'lib/anatomy-coordinates.ts']);
const ownRoot = fileURLToPath(new URL('../', import.meta.url));
const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const absolute = (root, relative) => path.join(root, ...relative.split('/'));
const digest = value => typeof value === 'string' && /^[a-f0-9]{64}$/.test(value);

export function declarationFor(catalogSha256, schemaSha256) {
  if (!digest(catalogSha256) || !digest(schemaSha256)) throw Error('Invalid catalog or contract digest');
  return '// Generated by scripts/native-catalog-types.mjs; do not hand edit.\n' +
    `// Catalog SHA-256: ${catalogSha256}\n// Contract SHA-256: ${schemaSha256}\n` +
    "import type {BodyCatalog} from '../../../../app/body-types';\n" +
    'declare const catalog: BodyCatalog;\nexport default catalog;\n';
}

/** Isolated full structural check; this program never enters the normal app type graph. */
export function validateCatalogContract(catalogText, atlasRoot = ownRoot) {
  if (typeof catalogText !== 'string') throw Error('Expected catalog JSON text');
  const parsed = JSON.parse(catalogText);
  if (parsed === null || Array.isArray(parsed) || typeof parsed !== 'object')
    throw Error('Expected a catalog object');
  const root = path.resolve(atlasRoot);
  const entry = path.join(root, '__native_catalog_contract__.ts');
  const text = "import type {BodyCatalog} from './app/body-types';\n" +
    'type DeepReadonly<T> = T extends object ? { readonly [P in keyof T]: DeepReadonly<T[P]> } : T;\n' +
    `const source = ${JSON.stringify(parsed)} as const;\n` +
    'const checked: DeepReadonly<BodyCatalog> = source;\nvoid checked;\n';
  const options = {target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler, strict: true, noEmit: true,
    types: [], lib: ['lib.es2022.d.ts'], skipLibCheck: false, incremental: false};
  const host = ts.createCompilerHost(options), originalGet = host.getSourceFile.bind(host);
  host.getSourceFile = (file, language, onError, fresh) => path.resolve(file) === entry
    ? ts.createSourceFile(file, text, language, true)
    : originalGet(file, language, onError, fresh);
  const program = ts.createProgram([entry], options, host);
  const actualSchema = program.getSourceFiles()
    .filter(file => !program.isSourceFileDefaultLibrary(file) && path.resolve(file.fileName) !== entry)
    .map(file => path.relative(root, file.fileName).split(path.sep).join('/')).sort();
  assert.deepEqual(actualSchema, [...schemaPaths].sort(), 'Catalog type dependency changed');
  const diagnostics = ts.getPreEmitDiagnostics(program);
  if (diagnostics.length) throw Error('Catalog does not satisfy BodyCatalog: ' +
    [...new Set(diagnostics.map(d => 'TS' + d.code))].join(', '));
  return {schemaPaths: [...schemaPaths], validated: true};
}

export function generateCatalogTypes({atlasRoot = ownRoot, check = false} = {}) {
  const root = path.resolve(atlasRoot);
  const config = JSON.parse(fs.readFileSync(absolute(root, 'tsconfig.json'), 'utf8'));
  assert.equal(config.compilerOptions?.resolveJsonModule, true, 'Enable JSON module resolution');
  assert.equal(config.compilerOptions?.allowArbitraryExtensions, true, 'Enable catalog declaration resolution');
  const bytes = fs.readFileSync(absolute(root, catalogPath));
  const catalogSha256 = sha(bytes);
  const schema = schemaPaths.map(relative => ({path: relative, sha256: sha(fs.readFileSync(absolute(root, relative)))}));
  const schemaSha256 = sha(JSON.stringify(schema));
  validateCatalogContract(bytes.toString('utf8'), root);
  const expected = declarationFor(catalogSha256, schemaSha256);
  const destination = absolute(root, declarationPath);
  if (check) assert.equal(fs.readFileSync(destination, 'utf8'), expected, 'Stale native catalog declaration');
  else fs.writeFileSync(destination, expected);
  return {checked: check, path: declarationPath, sourcePath: catalogPath, catalogSha256, schemaSha256};
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check'))
    throw Error('Usage: native-catalog-types.mjs [--check]');
  console.log(JSON.stringify(generateCatalogTypes({atlasRoot: process.env.VM_ATLAS_ROOT ?? ownRoot, check: args[0] === '--check'})));
}
