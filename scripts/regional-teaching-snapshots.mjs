import assert from 'node:assert/strict';
import {readFile, writeFile, mkdir, readdir} from 'node:fs/promises';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {build, stop} from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const outputDirectory = 'content/regional-teaching';
const standalone = Boolean(process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url));

/** Preserve own undefined fields without executable or ambiguous JSON markers. */
function encodeSnapshot(region, entries) {
  const undefinedPaths = [];
  function encode(value, path) {
    if (value === undefined) { undefinedPaths.push(path); return null; }
    if (Array.isArray(value)) return value.map((item, i) => encode(item, [...path, i]));
    if (value !== null && typeof value === 'object')
      return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, encode(item, [...path, key])]));
    return value;
  }
  return {schemaVersion:1, region, entries:encode(entries, ['entries']), undefinedPaths};
}

/** Derived exclusively from the existing display catalogue and complete resolver. */
export async function regionalTeachingOutputs() {
  const bundle = await build({
    absWorkingDir:root,
    stdin:{contents: `export {bodyLesson} from './app/body-content';
      export {bodyDisplayCatalog} from './lib/body-display-catalog';
      export {sourceCanonical} from './lib/body-source-additions';
      export {contentTabs} from './lib/content-types';
      export {decodeRegionalTeachingSnapshot} from './lib/regional-teaching-snapshot';`, resolveDir:root, loader:'ts'},
    bundle:true, write:false, platform:'node', format:'esm',
  }).finally(() => {
    // This CLI owns its bundler. Release the native service before materializing
    // all lessons; imported library callers keep their shared service untouched.
    if (standalone) return stop();
  });
  const api = await import('data:text/javascript;base64,' + Buffer.from(bundle.outputFiles[0].text).toString('base64'));
  const catalog = api.bodyDisplayCatalog(JSON.parse(await readFile(resolve(root, 'public/models/bodyparts3d/full-body/catalog.json'), 'utf8')));
  const groups = new Map();
  const identities = new Set();
  for (const structure of catalog.structures) {
    assert.match(structure.region, /^[a-z]+(?:-[a-z]+)*$/, 'Enumerated safe source region required');
    const identity = api.sourceCanonical(structure);
    assert(!identities.has(identity), 'Duplicate complete teaching identity');
    identities.add(identity);
    const entries = groups.get(structure.region) ?? [];
    entries.push({identity, lessons:Object.fromEntries(api.contentTabs.map(tab => [tab, api.bodyLesson(structure, tab)]))});
    groups.set(structure.region, entries);
  }
  const outputs = new Map();
  for (const [region, entries] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    const snapshot = encodeSnapshot(region, entries);
    // Prove the serialized representation, not just the in-memory generator.
    const reader = api.decodeRegionalTeachingSnapshot(JSON.parse(JSON.stringify(snapshot)), region);
    for (const structure of catalog.structures.filter(s => s.region === region))
      for (const tab of api.contentTabs)
        assert.deepEqual(reader.bodyLesson(structure, tab), api.bodyLesson(structure, tab));
    outputs.set(`${outputDirectory}/${region}.json`, JSON.stringify(snapshot) + '\n');
  }
  outputs.set('lib/regional-teaching-imports.ts',
    '// Generated by scripts/regional-teaching-snapshots.mjs; do not hand edit.\n' +
    '// Explicit imports are included in renderer and learner source revisions.\n' +
    'export const regionalTeachingImports: Record<string, () => Promise<{ default: unknown }>> = {\n' +
    [...groups.keys()].sort().map(region => `  ${JSON.stringify(region)}: () => import('../${outputDirectory}/${region}.json', { with: { type: 'json' } }),`).join('\n') + '\n};\n');
  return {outputs, structures:catalog.structures.length, lessons:catalog.structures.length * api.contentTabs.length, regions:groups.size};
}

/** Injectable read-only filesystem for negative tests; production uses real files. */
export async function checkRegionalTeachingOutputs(outputs, {read = readFile, list = readdir} = {}) {
  const unexpected = (await list(resolve(root, outputDirectory))).filter(name =>
    !outputs.has(`${outputDirectory}/${name}`));
  assert.deepEqual(unexpected, [], 'Unexpected regional teaching files need explicit review');
  for (const [path, expected] of outputs)
    assert.equal((await read(resolve(root, path), 'utf8')).replace(/\r\n/g, '\n'), expected,
      `Stale regional teaching: ${path}; run node scripts/regional-teaching-snapshots.mjs before review/build`);
}

export async function writeOrCheckRegionalTeaching({check = true} = {}) {
  const {outputs, ...counts} = await regionalTeachingOutputs();
  if (check) await checkRegionalTeachingOutputs(outputs);
  else {
    await mkdir(resolve(root, outputDirectory), {recursive:true});
    const unexpected = (await readdir(resolve(root, outputDirectory))).filter(name => !outputs.has(`${outputDirectory}/${name}`));
    assert.deepEqual(unexpected, [], 'Unexpected regional teaching files need explicit review');
  for (const [path, expected] of outputs) {
      await writeFile(resolve(root, path), expected);
    }
  }
  return {...counts, files:outputs.size, mode:check?'checked':'generated'};
}

if (standalone)
  console.log(JSON.stringify(await writeOrCheckRegionalTeaching({check:process.argv.includes('--check')})));
