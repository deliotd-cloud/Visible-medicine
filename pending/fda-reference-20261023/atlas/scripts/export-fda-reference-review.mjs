// Prepare material for a later protected Website integration. This writes no decisions.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {fileURLToPath,pathToFileURL} from 'node:url';
import {build} from 'esbuild';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sha=bytes=>createHash('sha256').update(bytes).digest('hex');
const files=['app/fda-shoulder-reference.tsx','app/fda-shoulder-reference.css','lib/fda-reference-model-loader.ts','lib/fda-shoulder-reference.ts','lib/fda-reference-review.ts'];
const output=process.argv[2];assert.equal(process.argv.length,3,'Usage: node scripts/export-fda-reference-review.mjs <NEW-external-output-directory>');
assert(output&&path.isAbsolute(output),'Explicit absolute output required');const out=path.resolve(output);
const relative=path.relative(root,out);assert(relative==='..'||relative.startsWith('..'+path.sep),'Review material must remain outside the source checkout');
assert(!fs.existsSync(out),'Do not overwrite existing review evidence');
const catalogueBytes=fs.readFileSync(root+'/public/models/fda-shoulder-draft/catalog.json');
assert.equal(sha(catalogueBytes),'56cf325c006a00e4349a6b45844797800a11c005448d32a08f40e64664288b44');
const catalogue=JSON.parse(catalogueBytes),asset=fs.readFileSync(root+'/public'+catalogue.bundle.url);
assert.equal(asset.length,catalogue.bundle.bytes);assert.equal(sha(asset),catalogue.bundle.sha256);
const rendererInputs=files.map(file=>({path:file,sha256:sha(fs.readFileSync(root+'/'+file))}));
const rendererSourceSha256=sha(Buffer.from(JSON.stringify(rendererInputs)));
fs.mkdirSync(out,{recursive:true});
const modulePath=out+'/review-adapter.mjs';
await build({entryPoints:[root+'/lib/fda-reference-review.ts'],outfile:modulePath,bundle:true,platform:'node',format:'esm',logLevel:'error'});
const {fdaReferenceReviewMaterial}=await import(pathToFileURL(modulePath).href);
const materials=await Promise.all(catalogue.structures.map(s=>fdaReferenceReviewMaterial(catalogue,s.id,rendererSourceSha256)));
assert.equal(new Set(materials.map(m=>m.revision)).size,6);assert(materials.every(m=>!m.clinicalApproval&&!m.decisionWritingEnabled&&!m.protectedWebsiteQueueIntegrated));
const receipt={schema:'vm-fda-reference-material-export/1',rendererInputs,rendererSourceSha256,catalogueSha256:sha(catalogueBytes),glbSha256:sha(asset),materials,protectedWebsiteQueueIntegrated:false,decisionWritingEnabled:false,clinicalApproval:false};
fs.writeFileSync(out+'/MATERIALS.json',JSON.stringify(receipt,null,2)+'\n',{flag:'wx'});
console.log(JSON.stringify({materials:6,uniqueRevisions:6,rendererSourceSha256,output:out+'/MATERIALS.json',sha256:sha(fs.readFileSync(out+'/MATERIALS.json')),protectedWebsiteQueueIntegrated:false}));
