import assert from 'node:assert/strict';
import test from 'node:test';
import {readFileSync} from 'node:fs';
import React from 'react';
import {renderToStaticMarkup} from 'react-dom/server';
import * as jsx from 'react/jsx-runtime';
import ts from 'typescript';
import {headAtlasConceptOptions,headConceptById,HEAD_LINK_REVISION} from '../lib/head-atlas-links.ts';
import {headImageHref} from '../lib/head-atlas-navigation.ts';
import {relatedLectureHref} from '../lib/lecture-related-links.ts';
import {LearningResourceStatus,LearningStatusKey} from '../components/LearningResourceStatus.ts';
import {headDisclosureKeyDown} from '../lib/head-disclosure-keyboard.ts';
const source=readFileSync(new URL('../components/HeadAtlasComparisonNavigation.tsx',import.meta.url),'utf8');
const ast=ts.createSourceFile('Navigation.tsx',source,ts.ScriptTarget.Latest,true,ts.ScriptKind.TSX);
const declarations=ast.statements.filter(s=>!ts.isImportDeclaration(s)&&!ts.isExpressionStatement(s)).map(s=>s.getText(ast)).join('\n');
const compiled=ts.transpileModule(declarations,{compilerOptions:{jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
type Node={type:unknown;props:Record<string,any>};
const walk=(value:any):Node[]=>Array.isArray(value)?value.flatMap(walk):value&&typeof value==='object'&&'props'in value?[value,...walk(value.props.children)]:[];
for(const reason of ['sign-in','access-denied'] as const)test(`${reason} navigation explains access without disclosing a comparison`,()=>{
 const exports:{HeadAtlasComparisonNavigation?:(props:any)=>React.ReactElement}={};
 const evaluate=new Function('exports','require','useRouter','headLinksCurrent','HEAD_LINK_REVISION_NOTICE','headAtlasConceptOptions','headConceptById','HeadAtlasLearningPicker','headImageHref','HEAD_LINK_REVISION','relatedLectureHref','LearningResourceStatus','LearningStatusKey','headDisclosureKeyDown',compiled);
 evaluate(exports,(id:string)=>{assert.equal(id,'react/jsx-runtime');return jsx;},()=>({push:()=>assert.fail('No navigation during access refusal')}),()=>true,'Revision changed.',headAtlasConceptOptions,headConceptById,()=>null,headImageHref,HEAD_LINK_REVISION,relatedLectureHref,LearningResourceStatus,LearningStatusKey,headDisclosureKeyDown);
 let retries=0,focus=0;
 const tree=exports.HeadAtlasComparisonNavigation!({conceptId:'brainstem-pons',liveState:reason,onRetry:()=>retries++});
 const html=renderToStaticMarkup(tree);assert.match(html,reason==='sign-in'?/Sign in to Visible Medicine/:/Access.*refused/);
 assert.match(html,/Atlas and imaging access are checked separately/);assert.match(html,/no matching model selection is confirmed/);
 assert.doesNotMatch(html,/<form|<select|Compare Pons on CT|Compare Pons on MRI|Links follow the selected structure/);
 const retry=walk(tree).find(node=>node.type==='button'&&node.props.children==='Check model access again');assert(retry);
 retry.props.onClick({currentTarget:{closest:()=>({focus:()=>focus++})}});assert.equal(retries,1);assert.equal(focus,1);
});
