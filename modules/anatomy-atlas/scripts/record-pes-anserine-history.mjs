import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {contentContext} from './content-contract-tools.mjs';
import {exactSourceHistoryApi} from './exact-source-history-api.mjs';
import {wholeBodyTeachingSnapshot} from './exact-clinical-reference-history.mjs';
const parentCommit='b2ecd5081cbba447515a3dbfbf38e3d0ca1da96a';
const ids=['right-pes-anserinus-muscle-convergence','left-pes-anserinus-muscle-convergence'];
const hash=v=>createHash('sha256').update(JSON.stringify(v)).digest('hex');
const [{api,catalog},prior]=await Promise.all([contentContext(),exactSourceHistoryApi(parentCommit)]);
assert.deepEqual(api.bodyDisplayCatalog(catalog),prior.bodyDisplayCatalog(catalog),'No catalogue or source identity changes');
const profiles=structuredClone(api.dissectionProfiles);
const additions=profiles['whole-body'].focuses.filter(f=>ids.includes(f.id));
assert.deepEqual(additions.map(f=>f.id),ids);
profiles['whole-body'].focuses=profiles['whole-body'].focuses.filter(f=>!ids.includes(f.id));
const url='https://anatomy.ttuhscep.edu/anatomytables/muscles_lowerlimb.html';
assert(!prior.dissectionProfiles['whole-body'].references.includes(url));
assert.equal(profiles['whole-body'].references.filter(r=>r===url).length,1);
const reference={url,index:profiles['whole-body'].references.indexOf(url)};
profiles['whole-body'].references.splice(reference.index,1);
assert.equal(hash(profiles),hash(prior.dissectionProfiles),'Only two focuses and their reference change');
assert.equal(hash(wholeBodyTeachingSnapshot({...api,dissectionProfiles:profiles},catalog)),hash(wholeBodyTeachingSnapshot(prior,catalog)),'All 9,936 topics and prior recipes remain exact');
const record={parentCommit,ids,reference,beforeHash:hash(profiles),afterHash:hash(api.dissectionProfiles),additionsHash:hash(additions),catalogHash:hash(api.bodyDisplayCatalog(catalog)),teachingAndPriorRecipesHash:hash(wholeBodyTeachingSnapshot(prior,catalog))};
const path='content/pes-anserine-study.transition.json',text=JSON.stringify(record,null,2)+'\n';
if(process.argv.includes('--check'))assert.equal((await readFile(path,'utf8')).replace(/\r\n/g,'\n'),text);
else await writeFile(path,text,{flag:'wx'});
console.log(JSON.stringify(record));
