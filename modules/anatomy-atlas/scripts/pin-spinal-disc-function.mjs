import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import {contentContext} from './content-contract-tools.mjs';
import {exactSourceHistoryApi} from './exact-source-history-api.mjs';
import {wholeBodyTeachingSnapshot} from './exact-clinical-reference-history.mjs';
const parentCommit='bff0cbb95f66c333846497d48b6503df07bd1ad3';
const hash=v=>createHash('sha256').update(JSON.stringify(v)).digest('hex');
const checking=process.argv.includes('--check');
if(!checking)assert.equal(execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),parentCommit);
const api=checking?await exactSourceHistoryApi(parentCommit):(await contentContext()).api;
const raw=JSON.parse(await readFile('public/models/bodyparts3d/full-body/catalog.json'));
const display=api.bodyDisplayCatalog(raw);
const existing=JSON.parse(await readFile('content/spine-imaging-pins.json'));
const groups=['cervicalDisc','thoracicDisc','lumbarDisc'];
const entries=existing.entries.filter(e=>groups.includes(e.group)).map(({identity,group})=>{
  assert.deepEqual(display.structures.find(s=>s.id===identity.id),identity);
  const previous={function:api.bodyLesson(identity,'function')};
  assert.equal(previous.function.title,'Whole intervertebral disc · draft');
  return {identity,group,previous};
});
assert.deepEqual(groups.map(g=>entries.filter(e=>e.group===g).length),[6,11,5]);
assert(!entries.some(e=>e.identity.sources.some(s=>s.file==='FJ3211')));
const pins={parentCommit,originalPinsHash:hash(existing),catalogHash:hash(display),previousAllLessonsAndRecipesHash:hash(wholeBodyTeachingSnapshot(api,raw)),entries};
const path='content/spinal-disc-function.before.json',text=JSON.stringify(pins,null,2)+'\n';
if(checking)assert.equal((await readFile(path,'utf8')).replace(/\r\n/g,'\n'),text);
else await writeFile(path,text,{flag:'wx'});
console.log(JSON.stringify({source:parentCommit,selections:entries.length,topics:entries.length,pinsHash:hash(pins),beforeHash:pins.previousAllLessonsAndRecipesHash}));
